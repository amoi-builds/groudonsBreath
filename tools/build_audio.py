"""Embed the ripped PMD Red Rescue Team audio in a script the page can load straight from file://
(browsers won't fetch() local files, and Web Audio needs the raw bytes for gapless looping).

Reads  assets/source/audio/*.mp3
Writes assets/audio.js

Run from the project root:  python3 -I tools/build_audio.py
"""
import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'source', 'audio')
OUT = os.path.join(ROOT, 'assets', 'audio.js')

CLIPS = {
    'music': 'versus_boss.mp3',              # BGM "Versus Boss"
    'flame': 'flamethrower_song674.mp3',     # Flamethrower's flame stream
    'burn': 'burn_song671.mp3',              # burn status inflicted
    'cursor': 'menu_cursor_song301.mp3',     # menu cursor move
    'confirm': 'menu_confirm_song302.mp3',   # menu confirm
}

with open(OUT, 'w') as f:
    f.write('// Generated by tools/build_audio.py. Do not edit.\n')
    f.write('window.AUDIO_DATA = {\n')
    for name, file in CLIPS.items():
        with open(os.path.join(SRC, file), 'rb') as clip:
            f.write("  %s: '%s',\n" % (name, base64.b64encode(clip.read()).decode('ascii')))
    f.write('};\n')

print('audio.js:', os.path.getsize(OUT), 'bytes')
